const supportedLanguages = {
  en: "English",
  it: "Italiano",
  es: "Español",
  fr: "Français",
  de: "Deutsch",
  pt: "Português",
  ja: "日本語",
  zh: "中文"
};

function detectLanguage() {
  const saved = localStorage.getItem("kcore-lang");
  if (saved && translations[saved]) return saved;

  const browserLangs = navigator.languages || [navigator.language || "en"];
  for (const lang of browserLangs) {
    const code = lang.split("-")[0].toLowerCase();
    if (translations[code]) return code;
  }
  return "en";
}

function t(key, lang) {
  return (translations[lang] && translations[lang][key]) ||
         translations.en[key] ||
         "";
}

function applyTranslations(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = t(key, lang);
    if (val) el.textContent = val;
  });

  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    const val = t(key, lang);
    if (val) el.innerHTML = val;
  });

  const switcher = document.getElementById("lang-current");
  if (switcher) {
    switcher.textContent = supportedLanguages[lang] || lang;
  }
}

function setLanguage(lang) {
  localStorage.setItem("kcore-lang", lang);
  applyTranslations(lang);
}

function buildLanguageSwitcher() {
  const nav = document.querySelector(".nav-menu");
  if (!nav) return;

  const li = document.createElement("li");
  li.className = "lang-switcher";

  const btn = document.createElement("button");
  btn.className = "lang-btn";
  btn.id = "lang-current";
  btn.textContent = "English";
  btn.setAttribute("aria-haspopup", "true");
  btn.setAttribute("aria-expanded", "false");

  const dropdown = document.createElement("ul");
  dropdown.className = "lang-dropdown";
  dropdown.setAttribute("role", "menu");

  for (const [code, name] of Object.entries(supportedLanguages)) {
    const item = document.createElement("li");
    item.setAttribute("role", "menuitem");
    const link = document.createElement("button");
    link.className = "lang-option";
    link.textContent = name;
    link.addEventListener("click", () => {
      setLanguage(code);
      dropdown.classList.remove("open");
      btn.setAttribute("aria-expanded", "false");
    });
    item.appendChild(link);
    dropdown.appendChild(item);
  }

  btn.addEventListener("click", (e) => {
    e.stopPropagation();
    const isOpen = dropdown.classList.toggle("open");
    btn.setAttribute("aria-expanded", isOpen);
  });

  document.addEventListener("click", () => {
    dropdown.classList.remove("open");
    btn.setAttribute("aria-expanded", "false");
  });

  li.appendChild(btn);
  li.appendChild(dropdown);
  nav.appendChild(li);
}

document.addEventListener("DOMContentLoaded", () => {
  buildLanguageSwitcher();
  const lang = detectLanguage();
  applyTranslations(lang);
});
